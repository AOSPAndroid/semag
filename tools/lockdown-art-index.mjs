#!/usr/bin/env node
/** Rebuild public/art/lockdown/index.json from the PNGs present, rewrite the art
 * brief (public/art/lockdown/ASSETS.md) with an up-to-date checklist, and report
 * which manifest sprites are still missing or have the wrong size. Run after adding art:
 *   node tools/lockdown-art-index.mjs */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { MANIFEST } from '../public/lockdown-assets.js';

const dir = fileURLToPath(new URL('../public/art/lockdown/', import.meta.url));
const pngSize = buffer => buffer.length > 24 && buffer.toString('ascii', 1, 4) === 'PNG' ? [buffer.readUInt32BE(16), buffer.readUInt32BE(20)] : null;
const files = (await readdir(dir)).filter(file => file.endsWith('.png'));
const present = [], problems = [];
for (const entry of MANIFEST) {
  if (!files.includes(entry.file)) continue;
  const size = pngSize(await readFile(dir + entry.file));
  // Art may be drawn at the listed size or at exactly 2x (HD, preferred): the game shows both at the listed size.
  const fits = size && [1, 2].some(k => size[0] === entry.size[0] * k && size[1] === entry.size[1] * k);
  if (!fits) problems.push(`${entry.file}: expected ${entry.size.join('x')} (or 2x: ${entry.size.map(n => n * 2).join('x')}), got ${size ? size.join('x') : 'not a PNG'}`);
  else present.push(entry.file);
}
await writeFile(dir + 'index.json', JSON.stringify({ files: present.sort() }, null, 2) + '\n');
await writeFile(dir + 'ASSETS.md', brief(new Set(present), problems));
const missing = MANIFEST.filter(entry => !files.includes(entry.file)).map(entry => entry.file);
console.log(`${present.length}/${MANIFEST.length} sprites ready.`);
if (problems.length) console.log(`Wrong size (left out until fixed):\n  ${problems.join('\n  ')}`);
if (missing.length) console.log(`Missing (placeholders used):\n  ${missing.join('\n  ')}`);

function brief(ready, problems) {
  const groups = [...new Set(MANIFEST.map(entry => entry.group))];
  const title = { tiles: 'Tiles', environment: 'Base landmarks and terrain borders', characters: 'Bare character body', armors: 'Armor overlays', gear: 'Helmets, pants and shoes (overlays)', weapons: 'Held weapons', projectiles: 'Projectiles', bombs: 'Bombs', effects: 'Effects', pickups: 'Pickups', points: 'Control points', icons: 'Icons' };
  const rows = group => MANIFEST.filter(entry => entry.group === group).map(entry => `| ${ready.has(entry.file) ? '✅' : '⬜'} | \`${entry.file}\` | ${entry.size.join('×')} | ${entry.frames}${entry.rows ? ` × ${entry.rows} rows` : ''} | ${entry.anchor.join(', ')} | ${entry.description.replace(/\|/g, '/')} |`).join('\n');
  return `# Lockdown art brief

<!-- Generated by tools/lockdown-art-index.mjs from public/lockdown-assets.js. Edit the manifest, not this file. -->

Lockdown is a top-down team brawl in the spirit of Spiral Knights' Lockdown: up to 4v4,
three control points, swords, guns and bombs. The game is fully playable with placeholder
shapes; every PNG listed below replaces one placeholder as soon as it is added.

**Progress: ${ready.size}/${MANIFEST.length} sprites ready.**${problems.length ? `\n\nWrong size (ignored until fixed):\n${problems.map(problem => `- ${problem}`).join('\n')}` : ''}

## Style guide

- **Camera:** ¾ view like Spiral Knights, light from the top-left. The game tilts the floor itself: everything lying flat
  is foreshortened to 75% of its depth (a 48×48 floor tile shows as 48×36, a round capture plate as an oval).
  - **Flat art** (floor, wall-top and pit tiles, point plate, floor rings, clouds, domes, slashes, blasts): draw it
    straight from above, undistorted. The game squashes it. Do not paint perspective into it.
  - **Upright art** (knights, gear, weapons, beacons, bombs, hearts, wall fronts, ledges, stairs): draw it as seen
    by the camera. The game shows it at full height.
- **Look (approved direction A, painted fantasy 3D):** rounded, smoothly shaded fantasy inspired by Spiral Knights: broad painted highlights,
  soft bevels and antialiased silhouettes. Avoid voxel cubes, pixel grids, harsh outlines and noisy textures.
  Make original characters and objects; use the reference game's shapes and materials as inspiration.
- **Terrain:** quiet painted floor textures, lighter wall tops and darker front faces.
  Tile materials join seamlessly; hazards sit below the walking surface and keep their edge shadows.
  Continuous ground paintings span 4×4 map cells and pit paintings span 3×3, keeping the paving broad and quiet.
  Architectural wall fronts span three cells and stand 72 px high; capped pillars, climbing vines and generous
  rounded border clumps match the approved concept. Visible cut banks sit below the walking surface.
  Each base has one continuous ivory court, an arched masonry recess, team banner posts and three heart stations.
  Foreground architecture fades where it would hide a nearby knight; collision and movement use the existing map.
- **Equipment:** all classes share the T-shirt-and-shorts body. Each armor is a separate transparent
  garment layer with the same 640×320 grid, row, frame, anchor and mirroring. Leave exposed body parts transparent.
  Armor contains no headgear, pants or shoes. Draw the body, armor, shoes, pants and helmet in that order;
  every layer follows the same pose. All sheets have ten columns of 64×64 frames: columns 1–2 idle,
  3–6 walk, and 7–10 run (contact, flight, opposite contact, opposite flight). Helmets, pants and shoes use neutral materials.
  Draw equipment as worn: heads hide the far side of open bands, and ankles enter shoe cuffs.
  Register shoe openings and soles to the actual leg pose; keep hidden rear surfaces transparent.
  Armor health bonuses add to class health; choosing equipment preserves class abilities.
- **Knights turn toward the mouse**, like Spiral Knights. Each sheet has 5 facing rows: down, down-right, right,
  up-right, up. The game mirrors the right-hand rows for the left-hand directions and never rotates a knight.
  Knights are drawn **empty-handed**: the game pins the weapon sprite to each row's hand point and rotates it to the aim
  (behind the body when the knight faces away).
- **Orientation:** everything else that rotates (held weapons, projectiles, slashes, muzzle flashes)
  is drawn **facing right (+x)**. The game rotates it to the aim direction.
- **Anchor:** the pivot pixel (from the top-left) the game places on the world position and rotates around.
- **Sheets:** animation frames run left to right in equal cells; knight sheets stack one facing per row.
- **Scale:** draw at world scale (1 px = 1 world unit; the camera zooms the whole scene). A floor tile is 48 px;
  a knight is about 36 px wide and 50 px tall, with feet on the anchor point.
- **Team colours:** Amber \`#e39a3b\` (team 0) and Cyan \`#3bb8c4\` (team 1). Only sprites whose name says
  \`team0\`/\`team1\` carry team colour; everything else stays neutral and the game adds a coloured ring.
- **Format:** 32-bit PNG with transparency, at exactly **2x** the pixel sizes below (HD, preferred: the game shows it at the listed size with twice the detail) or exactly 1x. Any other size is skipped.
- **Bases:** each team's spawn tiles (\`tile_spawn_team0/1\`) are its base, where knights heal and change loadout; make them read as a safe zone.
- **Themes:** \`castle\` (Old Keep, flagstones and moat), \`maze\` (Hedge Labyrinth, earth and hedges),
  \`foundry\` (Clockwork Foundry, iron and lava), \`ruins\` (Sunken Temple, sandstone and pools),
  \`graveyard\` (Gloom Graveyard, slate and crypts), and \`skyway\` (Sky Bridges, pale stone above clouds).

## How to deliver

1. Save each PNG in \`public/art/lockdown/\` with the exact file name.
2. Run \`node tools/lockdown-art-index.mjs\`. It checks sizes, updates \`index.json\` (which the game reads
   to decide what to load) and refreshes the checklist below.
3. Open \`/lockdown.html\` (practice runs offline with bots) to check the result in game.

${groups.map(group => `## ${title[group] || group}

| | File | Size (px) | Frames | Anchor | Notes |
|---|---|---|---|---|---|
${rows(group)}`).join('\n\n')}
`;
}
